#!/bin/bash
# Lightweight assert: BOARD-RECOVERY.md (+ BOARD-CHECKLIST) script/doc entry points
# resolve to real files under lite/; cross-check qemu-ide verify names and package README keys.
# No network. Exit 0 = consistent; 1 = drift.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
LITE=$(cd "$HERE/../.." && pwd)
ROOT=$(cd "$LITE/.." && pwd)
REC=${BOARD_RECOVERY:-$LITE/docs/BOARD-RECOVERY.md}
CHK=${BOARD_CHECKLIST:-$LITE/docs/BOARD-CHECKLIST.md}
QEMU_README=$LITE/test/qemu-ide/README.md
PKG_README=${PKG_README:-}  # optional handoff README
R=0
pass(){ echo "[PASS] $*"; }
fail(){ echo "[FAIL] $*"; R=1; }
warn(){ echo "[WARN] $*"; }

echo "==== check-board-recovery-refs $(date '+%Y-%m-%d %H:%M:%S %z') ===="
[ -f "$REC" ] || { echo "missing $REC"; exit 2; }
[ -f "$CHK" ] || warn "BOARD-CHECKLIST.md missing at $CHK"

# --- A) scripts named in BOARD-RECOVERY must exist ---
# Extract *.sh / *.ps1 tokens from recovery doc
mapfile -t SCRIPTS < <(grep -oE '[A-Za-z0-9_./-]+\.(sh|ps1)' "$REC" | sed 's|^\./||' | sort -u)
declare -A FOUND
resolve() {
  local s=$1
  local c
  for c in \
    "$LITE/tools/board/$s" \
    "$LITE/test/qemu-ide/$s" \
    "$LITE/ci/$s" \
    "$LITE/docs/$s" \
    "$ROOT/$s" \
    "$HERE/$s"
  do
    if [ -f "$c" ]; then echo "$c"; return 0; fi
  done
  # basename-only search under lite/
  local hit
  hit=$(find "$LITE" -name "$(basename "$s")" -type f 2>/dev/null | head -1 || true)
  [ -n "$hit" ] && { echo "$hit"; return 0; }
  return 1
}

for s in "${SCRIPTS[@]}"; do
  # skip obvious non-repo patterns
  case "$s" in
    swap-libs.ps1) ;; # generated by pack-debug-libs
    *) ;;
  esac
  if path=$(resolve "$s"); then
    pass "recovery ref $s → $path"
    FOUND["$s"]=1
  else
    # swap-libs.ps1 is generated — warn only
    if [ "$(basename "$s")" = "swap-libs.ps1" ]; then
      warn "recovery mentions swap-libs.ps1 (generated by pack-debug-libs; OK)"
    else
      fail "recovery ref missing: $s"
    fi
  fi
done

# --- B) required UC entry scripts always present ---
REQUIRED=(
  verify-ide-contract-oneshot.sh
  verify.sh
  verify-contract.sh
  smoke-qemu-edges.sh
  soak-ide-contract.sh
  verify-jsdebug.sh
  verify-jsdebug-marker.sh
  verify-acedbg-gate.sh
  board-check.ps1
  setup-usb-gadget.sh
  from-board-results.sh
  check-host-hdc-ver.sh
  run-qemu-hdcd.sh
)
for s in "${REQUIRED[@]}"; do
  if path=$(resolve "$s"); then
    pass "required entry $s"
    # Must be mentioned in BOARD-RECOVERY for the core qemu/board set
    case "$s" in
      verify.sh|verify-ide-contract-oneshot.sh|smoke-qemu-edges.sh|soak-ide-contract.sh|verify-jsdebug.sh|verify-jsdebug-marker.sh|board-check.ps1|setup-usb-gadget.sh|from-board-results.sh)
        grep -q "$s" "$REC" && pass "BOARD-RECOVERY mentions $s" || fail "BOARD-RECOVERY omits $s"
        ;;
    esac
  else
    fail "required entry missing on disk: $s"
  fi
done

# --- C) BOARD-CHECKLIST USB IDs U1–U8 still present ---
if [ -f "$CHK" ]; then
  for u in U1 U2 U3 U4 U5 U6 U7 U8; do
    grep -qE "\\b$u\\b" "$CHK" && pass "CHECKLIST has $u" || fail "CHECKLIST missing $u"
  done
  for u in U1 U2 U3 U4 U5 U8; do
    grep -qE "\\b$u\\b" "$REC" && pass "RECOVERY has $u" || fail "RECOVERY missing $u (USB table)"
  done
fi

# --- D) qemu-ide README lists negatives / edges ---
if [ -f "$QEMU_README" ]; then
  grep -q 'smoke-qemu-edges' "$QEMU_README" && pass "qemu README lists smoke-qemu-edges" || fail "qemu README missing smoke-qemu-edges"
  grep -qE 'verify-ide-contract-oneshot|verify-contract' "$QEMU_README" && pass "qemu README lists contract verifies" || fail "qemu README missing contract verifies"
fi

# --- E) optional package README cross-check ---
for cand in "$PKG_README" "$ROOT/../handoff-2026-10-29/README.md" /workspace/hdcd-port/handoff-2026-10-29/README.md; do
  if [ -n "${cand:-}" ] && [ -f "$cand" ]; then
    PKG_README=$cand
    break
  fi
done
if [ -n "${PKG_README:-}" ] && [ -f "$PKG_README" ]; then
  for key in BOARD-RECOVERY.md verify-ide-contract-oneshot.sh soak-ide-contract.sh smoke-qemu-edges; do
    grep -q "$key" "$PKG_README" && pass "package README mentions $key" || fail "package README missing $key"
  done
else
  warn "no package README found — skip package cross-check"
fi

# --- F) ide-error-codes linked from recovery ---
grep -q 'ide-error-codes' "$REC" && pass "RECOVERY links ide-error-codes" || fail "RECOVERY missing ide-error-codes link"

echo "RESULT=$R"
exit $R
